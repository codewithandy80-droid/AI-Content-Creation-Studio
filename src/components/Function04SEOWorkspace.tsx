          output_type: 'seo',
          version_number: newVersionNum,
          status: 'approved',
          content: {
            type: 'seo',
            data: currentContent,
          },
          analysis_version_id: approvedAnalysis.analysis_version_id,
          master_rules_version_id: activeProject.master_rules_version_id || DEFAULT_MASTER_RULES_V1.master_rules_version_id,
